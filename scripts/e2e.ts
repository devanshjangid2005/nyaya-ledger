/**
 * End-to-end check in a real headless Chrome, as a phone (412×915).
 * Flow: open → Kannada → "Try with demo data" → correct one number → confirm → docket → print to PDF.
 * Run: npm run e2e -- http://localhost:8787      (or the Render URL)
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { launch } from "./cdp.js";

const base = process.argv[2] ?? "http://localhost:8787";
const out = new URL("../demo/e2e/", import.meta.url);
mkdirSync(out, { recursive: true });
const save = (name: string, buf: Buffer) => writeFileSync(new URL(name, out), buf);

const fails: string[] = [];
const check = (ok: boolean, msg: string) => {
  console.log(`  ${ok ? "✓" : "✗"} ${msg}`);
  if (!ok) fails.push(msg);
};

const b = await launch();
try {
  await b.cdp("Page.enable");
  await b.cdp("Emulation.setDeviceMetricsOverride", { width: 412, height: 915, deviceScaleFactor: 2, mobile: true });
  await b.cdp("Page.navigate", { url: base });
  await b.waitFor(`document.querySelector('h1')?.textContent==='Nyaya-Ledger'`, "app loaded", 90_000);
  check(true, `app loaded at ${base}`);
  await b.setValue("select", "kn");
  await b.waitFor(`document.body.innerText.includes('ಡೆಮೊ ಡೇಟಾ ಬಳಸಿ')`, "Kannada UI");
  save("1-collect.png", await b.screenshot());

  await b.clickText("ಡೆಮೊ ಡೇಟಾ ಬಳಸಿ");
  await b.waitFor(`!!document.querySelector('input[aria-label="net payout"]')`, "confirm screen");
  check((await b.evaluate(`document.querySelectorAll('.card').length`)) >= 4, "confirm shows statements, notice and bank credits");
  const imgs = await b.evaluate(
    `Promise.all([...document.querySelectorAll('img.thumb')].map(i=>i.complete?i.naturalWidth>0:new Promise(r=>{i.onload=()=>r(true);i.onerror=()=>r(false)}))).then(a=>a.length+':'+a.every(Boolean))`,
  );
  check(imgs === "3:true", `3 demo screenshots load (${imgs})`);
  check((await b.evaluate(`document.querySelectorAll('.credit').length`)) === 3, "3 bank credits parsed from SMS");

  // The "fix a misread number" moment: wrong value, then corrected.
  await b.setValue('input[aria-label="net payout"]', "6015");
  await b.setValue('input[aria-label="net payout"]', "6105");
  save("2-confirm.png", await b.screenshot());

  await b.clickText("ಈ ಸಂಖ್ಯೆಗಳು ಸರಿಯಾಗಿವೆ");
  await b.waitFor(`document.querySelectorAll('.finding').length>0`, "docket", 150_000);
  const text: string = await b.evaluate(`document.body.innerText`);
  const issues = await b.evaluate(`document.querySelectorAll('.finding.possible_issue').length`);
  check(issues === 5, `5 possible issues (got ${issues})`);
  check(text.includes("₹100"), "C7: bank received ₹100 less");
  check(text.includes("₹120"), "C2: ₹120 gap");
  check(text.includes("Section 14(2)"), "Act s.14(2) quoted verbatim");
  check(text.includes("sms-5"), "SMS evidence listed");
  console.log(`  · docket generated by: ${text.includes("AI ಇಲ್ಲದೆ") ? "fallback (no AI configured)" : "Cline SDK agent"}`);
  save("3-result.png", await b.screenshot());
  const pdf = await b.pdf();
  save("docket.pdf", pdf);
  check(pdf.length > 10_000, `print → PDF docket (${Math.round(pdf.length / 1024)} KB)`);
} catch (e) {
  check(false, (e as Error).message);
  save("error.png", await b.screenshot().catch(() => Buffer.alloc(0)));
} finally {
  b.close();
}
console.log(fails.length ? `\nE2E FAILED (${fails.length})` : "\nE2E PASSED · screenshots + docket.pdf in demo/e2e/");
process.exit(fails.length ? 1 : 0);
